#!/usr/bin/env python3
"""Проверки стресс-теста правил пула (`pool_stress.py`).

Данные синтетические, ответ известен заранее. Каждая проверка названа по правилу, которое держит:
снятие правила обязано её краснить (стенд поломок — `mut_pool_stress.py`).

    python3 test_pool_stress.py
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
import pool_stress as PS                                               # noqa: E402

T0 = 1760054400          # 2025-10-10 00:00 UTC
LEV, DL, MDD, MM, TAKER = 5.0, 0.03, 0.06, 0.02, 4.5
FEE = TAKER / 1e4 * LEV                                                # доля капитала места на закрытие


def bar(rows, t0: int = T0) -> dict:
    """rows: (open, high, low, close) по минутам."""
    a = np.array(rows, dtype=float)
    return {"ts": (t0 + np.arange(len(a)) * 60).astype(np.int64),
            "o": a[:, 0], "h": a[:, 1], "l": a[:, 2], "c": a[:, 3]}


def ep(b, i=0, side=1, *, lag=1, snapshot=100.0, start=100.0, lev=LEV, dl=DL, mdd=MDD, mm=MM,
       exec_mode="open"):
    return PS.episode(b, i, side, lev=lev, daily_loss=dl, max_dd=mdd, snapshot=snapshot,
                      start_eq=start, lag=lag, taker_bps=TAKER, mm=mm, exec_mode=exec_mode)


def close(x: float, y: float, eps: float = 1e-9) -> bool:
    return abs(x - y) <= eps


def write_npz(d: Path, sym: str, rows, t0: int = T0) -> None:
    a = np.array(rows, dtype=float)
    np.savez(d / f"{sym}.npz", ts=(t0 + np.arange(len(a)) * 60).astype(np.int64),
             open=a[:, 0], high=a[:, 1], low=a[:, 2], close=a[:, 3], volume=np.ones(len(a)))


def main() -> int:
    fails: list[str] = []
    flat = (100.0, 100.0, 100.0, 100.0)

    # 1. Цена линии: при плече 5 дневной убыток 3 % эквити = 0.6 % цены.
    if not close(PS.line_price(100.0, 1, LEV, DL), 99.4):
        fails.append(f"линия лонга не на 0.6 % ниже входа: {PS.line_price(100.0, 1, LEV, DL)}")
    if not close(PS.line_price(100.0, -1, LEV, DL), 100.6):
        fails.append(f"линия шорта не на 0.6 % выше входа: {PS.line_price(100.0, -1, LEV, DL)}")

    # 2. Идеальный сторож (задержка 0) без гэпа: убыток ровно линия плюс комиссия, перелёта по цене нет.
    #    Минута пробития ЗАКРЫВАЕТСЯ ВЫШЕ линии: правило рубит фитиль, а не закрытие.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), flat])
    r = ep(b, lag=0)
    if not (r["пробито"] and close(r["итог_доля"], -(DL + FEE))):
        fails.append(f"мгновенный сторож теряет не 3 % + комиссия: {r}")
    if not close(r["перелёт_доля"], FEE):
        fails.append(f"перелёт мгновенного сторожа не равен комиссии: {r['перелёт_доля']}")

    # 3. Задержка 1 минута: выход по ОТКРЫТИЮ следующей минуты, убыток = плечо × ход цены.
    #    Открытие и закрытие этой минуты РАЗНЫЕ: выход по закрытию дал бы другое число.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (95.0, 96.5, 95.0, 96.5)])
    r = ep(b, lag=1)
    if not close(r["итог_доля"], -(LEV * 0.05 + FEE)):
        fails.append(f"задержка 1: выход не по открытию следующей минуты: {r}")
    if not close(r["перелёт_доля"], (1 - DL) - (1 - LEV * 0.05 - FEE)):
        fails.append(f"перелёт считается не от линии: {r['перелёт_доля']}")

    # 4. Задержка 2 минуты берёт минуту ещё дальше.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (99.0, 99.0, 99.0, 99.0), (97.0, 97.0, 97.0, 97.0)])
    if not close(ep(b, lag=2)["итог_доля"], -(LEV * 0.03 + FEE)):
        fails.append(f"задержка 2 берёт не ту минуту: {ep(b, lag=2)}")

    # 5. Статическая просадка 6 % связывает, когда снимок на полночь НИЖЕ капитала места:
    #    дневная линия 95×0.97 = 92.15 ниже статической 94, значит рубит статическая.
    b = bar([flat, (99.0, 99.0, 97.0, 97.5), flat])
    r = ep(b, lag=0, snapshot=95.0)
    if not (r["пробито"] and close(r["линия_доля"], -MDD)):
        fails.append(f"статическая линия 6 % не связывает при снимке 95: {r}")

    # 6. Дневная линия считается от СНИМКА, а не от капитала: снимок 104 ⇒ линия 100.88 уже выше
    #    эквити 100, места в сделке быть не может.
    if ep(bar([flat, flat]), snapshot=104.0).get("вход") is not None:
        fails.append("вход разрешён, когда линия уже пробита до входа")

    # 7. Ликвидация биржей: глубокий ход обрезает убыток уровнем ликвидации, а не ходом цены.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (50.0, 50.0, 50.0, 50.0)])
    r = ep(b, lag=1)
    p_liq = PS.liq_price(100.0, 1, LEV, MM)
    want = -(1.0 - (1.0 + LEV * (p_liq / 100.0 - 1.0)) + FEE)
    if not (r["ликвидация"] and close(r["итог_доля"], want)):
        fails.append(f"убыток не обрезан уровнем ликвидации: {r}, ждали {want}")
    if r["итог_доля"] < -1.0:
        fails.append(f"место потеряло больше своего капитала: {r['итог_доля']}")

    # 7а. Без поддерживающей маржи (--mm 0) уровень ликвидации совпадает с нулём эквити: убыток
    #     обязан упереться ровно в капитал места. Комиссия сверх нуля означала бы долг пула бирже.
    r0 = ep(b, lag=1, mm=0.0)
    if not close(r0["итог_доля"], -1.0):
        fails.append(f"при mm=0 место теряет не ровно свой капитал: {r0['итог_доля']}")

    # 8. Уровень ликвидации по определению: эквити / номинал = поддерживающая маржа.
    for side in (1, -1):
        p = PS.liq_price(100.0, side, LEV, MM)
        eq = 1.0 + LEV * side * (p / 100.0 - 1.0)
        if not close(eq / (LEV * p / 100.0), MM, 1e-12):
            fails.append(f"уровень ликвидации не даёт mm={MM} (сторона {side}): {eq / (LEV * p / 100.0)}")

    # 9. 🔴 Путь до закрытия кончается НА закрытии: при мгновенном стороже минимум минуты пробития
    #    принадлежит уже закрытой позиции. Иначе сторож, успевший на линии, всё равно «ликвидируется».
    b = bar([flat, (99.8, 99.9, 50.0, 99.6), flat])
    r = ep(b, lag=0)
    if r["ликвидация"] or not close(r["итог_доля"], -(DL + FEE)):
        fails.append(f"мгновенный сторож ликвидирован минимумом минуты, в которой его уже нет: {r}")

    # 10. Гэп ЧЕРЕЗ линию: минута открылась ниже линии — даже мгновенный сторож выходит по открытию.
    b = bar([flat, (98.0, 98.0, 97.5, 97.8), flat])
    r = ep(b, lag=0)
    if not close(r["итог_доля"], -(LEV * 0.02 + FEE)):
        fails.append(f"гэп через линию исполнен по линии, а не по открытию: {r}")
    if r["перелёт_доля"] <= FEE:
        fails.append("гэп через линию не даёт перелёта")

    # 11. Шорт зеркален: линия сверху, рубит рост цены.
    b = bar([flat, (100.2, 101.0, 100.1, 100.8), flat])
    r = ep(b, side=-1, lag=0)
    if not (r["пробито"] and close(r["итог_доля"], -(DL + FEE))):
        fails.append(f"шорт не рубится ростом цены: {r}")
    if ep(bar([flat, (99.0, 99.0, 98.0, 98.0), flat]), side=-1, lag=0)["пробито"]:
        fails.append("шорт пробит падением цены")

    # 12. Правило не пробито — держим до конца суток, платим только комиссию.
    b = bar([flat, (100.0, 100.1, 99.9, 100.0), (100.0, 100.0, 100.0, 100.0)])
    r = ep(b, lag=1)
    if r["пробито"] or not close(r["итог_доля"], -FEE):
        fails.append(f"без пробития правила место что-то потеряло: {r}")

    # 13. Прибыльная сделка не считается пробитием и не даёт перелёта.
    b = bar([flat, (101.0, 101.0, 100.9, 101.0), (102.0, 102.0, 102.0, 102.0)])
    r = ep(b, lag=1)
    if r["пробито"] or r["итог_доля"] <= 0:
        fails.append(f"растущий лонг закрыт по правилу: {r}")

    # 13а. 🔴 Закрытие по открытию следующей минуты — НЕ верхняя граница: на отскоке место выходит
    #      лучше линии, а бывает и в плюс. Так было с BTC 10.10.2025 в минуту 21:18.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (101.0, 101.0, 101.0, 101.0)])
    r = ep(b, lag=1)
    if not (r["пробито"] and r["итог_доля"] > 0):
        fails.append(f"выход на отскоке не даёт места в плюсе — граница считается неверно: {r}")

    # 13б. Режим worst берёт худшую цену ВСЕГО окна задержки, а не только минуты выхода: здесь
    #      худшая цена стоит в минуте ПРОБИТИЯ, и взять её обязан именно он.
    b = bar([flat, (99.8, 99.9, 90.0, 99.6), (99.5, 99.5, 99.0, 99.5)])
    r_open = ep(b, lag=1, exec_mode="open")
    r_worst = ep(b, lag=1, exec_mode="worst")
    if not close(r_open["итог_доля"], -(LEV * 0.005 + FEE)):
        fails.append(f"режим open взял не открытие минуты k: {r_open}")
    if not close(r_worst["итог_доля"], -(LEV * 0.10 + FEE)):
        fails.append(f"режим worst взял не худшую цену окна: {r_worst}")
    if not r_worst["перелёт_доля"] > r_open["перелёт_доля"]:
        fails.append("режим worst не хуже режима open")

    # 13в. 🔴 Путь до ликвидации кончается на цене ВЫХОДА: если сторож вышел ниже уровня
    #      ликвидации, значит биржа успела раньше, и убыток обрезан её уровнем, а не ходом цены.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (99.5, 99.5, 70.0, 99.5)])
    r = ep(b, lag=1, exec_mode="worst")
    p_liq2 = PS.liq_price(100.0, 1, LEV, MM)
    want2 = -(1.0 - (1.0 + LEV * (p_liq2 / 100.0 - 1.0)) + FEE)
    if not (r["ликвидация"] and close(r["итог_доля"], want2)):
        fails.append(f"выход ниже уровня ликвидации не обрезан этим уровнем: {r}, ждали {want2}")

    # 14. Сводка: перелёт берётся только по пробитым эпизодам, доля «хуже просадки» — по всем.
    s = PS.summarise([{"пробито": True, "итог_доля": -0.10, "перелёт_доля": 0.04, "ликвидация": False},
                      {"пробито": False, "итог_доля": -0.001, "перелёт_доля": 0.0, "ликвидация": False}],
                     MDD, "проба")
    if not (close(s["перелёт_средн_пп"], 4.0) and close(s["хуже_просадки_%"], 50.0)):
        fails.append(f"сводка считает перелёт или долю хуже просадки не по тем эпизодам: {s}")

    with tempfile.TemporaryDirectory() as td:
        d = Path(td)
        PS.DATA = str(d)
        # Сутки: ровная ночь, затем обвал на 20 % за минуту 61 и возврат.
        crash = [flat] * 61 + [(100.0, 100.0, 80.0, 82.0)] + [(82.0, 82.0, 82.0, 82.0)] * 60
        calm = [flat] * 122
        for s in ("AAAUSDT", "BBBUSDT", "CCCUSDT", "DDDUSDT", "EEEUSDT"):
            write_npz(d, s, crash)
        write_npz(d, "ZZZUSDT", calm, T0 + 86400)
        write_npz(d, "TWOUSDT", crash + [flat] * (1640 - len(crash)), T0)   # ряд идёт в следующие сутки

        # 15. Сутки грузятся окном UTC и только своим: ряд длиннее суток режется по верхней границе.
        if PS.load_day("AAAUSDT", T0 + 86400) is not None:
            fails.append("load_day отдал сутки, которых у монеты нет")
        if len(PS.load_day("AAAUSDT", T0)["o"]) != len(crash):
            fails.append("load_day режет сутки")
        two = PS.load_day("TWOUSDT", T0)
        if len(two["o"]) != 1440:
            fails.append(f"load_day взял не одни сутки: минут {len(two['o'])}")

        # 16. Худшие сутки — по средней просадке от открытия: обвальные раньше спокойных.
        w = PS.worst_days(["AAAUSDT", "ZZZUSDT"], "2025-10-10", 2)
        if w[0] != "2025-10-10":
            fails.append(f"худшие сутки отсортированы не по просадке: {w}")

        # 17. Пул: пять мест на пяти монетах, обвал общий — пробивает все пять, убыток складывается
        #     по капиталу мест, а не по числу мест.
        rep = PS.seats_report(["2025-10-10"], ["AAAUSDT", "BBBUSDT", "CCCUSDT", "DDDUSDT", "EEEUSDT"],
                              side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1, taker_bps=TAKER,
                              mm=MM, mode="minute")
        if len(rep) != 1:
            fails.append(f"отчёт по пулу пуст: {rep}")
        else:
            r = rep[0]
            if r["мест_пробито_в_худшем"] != 5:
                fails.append(f"общий обвал пробил не все пять мест: {r}")
            worst_share = r["худший_убыток_%_капитала_мест"] / 100.0
            per_seat = LEV * 0.20 + FEE                     # ход 20 % при плече 5 обрежется ликвидацией
            cap = 1.0 - (1.0 + LEV * (PS.liq_price(100.0, 1, LEV, MM) / 100.0 - 1.0)) + FEE
            if not close(worst_share, min(per_seat, cap), 5e-3):
                fails.append(f"убыток пула не равен убытку мест: {worst_share} против {min(per_seat, cap)}")
            if r["все_пять_пробиты_%"] < 50.0:
                fails.append(f"общий обвал не виден как одновременное пробитие: {r}")

    print(f"проверок в файле: 21 · провалов: {len(fails)}")
    for f in fails:
        print("•", f)                                       # «•» читает стенд поломок mut_pool_stress.py
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
